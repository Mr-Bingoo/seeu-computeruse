PATTERNS = [
    (r"(\S+) 在 \(([^)]*)\) 没有窗口", r"\1 has no window at (\2)"),
    (r"等 ([\d.]+) 秒画面没变", r"waited \1 s with no screen change"),
    (r"(\S+) ([\d.]+) 秒没拉起来", r"\1 didn't start within \2 s"),
    (r"(\S+) ([\d.]+) 秒没回话", r"\1 got no reply within \2 s"),
    (r"(\S+) ([\d.]+) 秒没退出", r"\1 didn't quit within \2 s"),
]
_ORDER = sorted(PHRASES, key=lambda p: len(p[0]), reverse=True)
_PUNCT = str.maketrans({"，": ", ", "。": ". ", "；": "; ", "：": ": ", "、": ", ", "（": " (", "）": ")", "「": " \"", "」": "\" ",
                        "？": "? ", "！": "! "})
_CJK = re.compile(r"[一-鿿]")


def to_en(text):
    """把一段结果文字里认得的中文换成英文;没有中文就原样返回。"""
    if not isinstance(text, str) or not _CJK.search(text):
        return text
    for pat, rep in PATTERNS:
        text = re.sub(pat, rep, text)
    for zh, en in _ORDER:
        if zh in text:
            text = text.replace(zh, en)
    text = text.translate(_PUNCT)
    text = re.sub(r",(?=[^\s\d])", ", ", text)              # 英文逗号后补空格(数字坐标里的不动)
    text = re.sub(r"(?<=[A-Za-z\"])\(", " (", text)           # 词后面紧贴的括号前补空格
    text = re.sub(r"(?<=\d)\(", " (", text)
    text = re.sub(r" +([,.;:)])", r"\1", text)                 # 标点前多出来的空格去掉
    text = re.sub(r"\.\s*\.", ".", text)
    return re.sub(r"  +", " ", text).strip()
